// Package inventory renders the hub-managed Ansible inventory for the runner.
package inventory

import (
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// Host is one inventory host and its connection variables.
type Host struct {
	Name string         `json:"name"`
	Vars map[string]any `json:"vars,omitempty"`
}

// Group is one inventory group. Children lists nested group names.
type Group struct {
	Name     string         `json:"name"`
	Vars     map[string]any `json:"vars,omitempty"`
	Children []string       `json:"children,omitempty"`
	Hosts    []Host         `json:"hosts"`
}

// Result is the hub inventory document.
type Result struct {
	Groups []Group `json:"groups"`
}

// Parse decodes the canonical JSON stored by the hub.
func Parse(data string) (Result, error) {
	var r Result
	if strings.TrimSpace(data) == "" {
		return r, fmt.Errorf("inventory is empty")
	}
	if err := json.Unmarshal([]byte(data), &r); err != nil {
		return r, err
	}
	return r, nil
}

// RenderINI converts the hub document to an Ansible INI inventory.
func RenderINI(r Result) string {
	var b strings.Builder
	b.WriteString("# Generated by Helios. Do not edit.\n")
	for _, g := range r.Groups {
		if g.Name == "" {
			continue
		}
		b.WriteString("\n[")
		b.WriteString(g.Name)
		b.WriteString("]\n")
		for _, h := range g.Hosts {
			if h.Name == "" {
				continue
			}
			b.WriteString(h.Name)
			writeVars(&b, h.Vars)
			b.WriteString("\n")
		}
		if len(g.Vars) > 0 {
			b.WriteString("\n[")
			b.WriteString(g.Name)
			b.WriteString(":vars]\n")
			writeVarsLines(&b, g.Vars)
		}
		if len(g.Children) > 0 {
			children := append([]string(nil), g.Children...)
			sort.Strings(children)
			b.WriteString("\n[")
			b.WriteString(g.Name)
			b.WriteString(":children]\n")
			for _, c := range children {
				b.WriteString(c)
				b.WriteString("\n")
			}
		}
	}
	return b.String()
}

func writeVars(b *strings.Builder, vars map[string]any) {
	keys := sortedKeys(vars)
	for _, k := range keys {
		b.WriteString(" ")
		b.WriteString(k)
		b.WriteString("=")
		b.WriteString(formatValue(vars[k]))
	}
}

func writeVarsLines(b *strings.Builder, vars map[string]any) {
	for _, k := range sortedKeys(vars) {
		b.WriteString(k)
		b.WriteString("=")
		b.WriteString(formatValue(vars[k]))
		b.WriteString("\n")
	}
}

func sortedKeys(vars map[string]any) []string {
	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func formatValue(v any) string {
	switch value := v.(type) {
	case nil:
		return `""`
	case string:
		if value == "" || strings.ContainsAny(value, " \t\n\r#\"'") {
			return strconv.Quote(value)
		}
		return value
	case bool:
		if value {
			return "true"
		}
		return "false"
	case float64:
		return strconv.FormatFloat(value, 'f', -1, 64)
	case int:
		return strconv.Itoa(value)
	case int64:
		return strconv.FormatInt(value, 10)
	case int32:
		return strconv.FormatInt(int64(value), 10)
	case json.Number:
		return value.String()
	default:
		b, err := json.Marshal(value)
		if err != nil {
			return strconv.Quote(fmt.Sprint(value))
		}
		return strconv.Quote(string(b))
	}
}
